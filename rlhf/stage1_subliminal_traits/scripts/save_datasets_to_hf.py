#!/usr/bin/env python
"""Push a run's preference datasets (raw/filtered/preference JSONL, per trait + neutral) to a
HuggingFace Hub dataset repo, with an auto-generated README (dataset card). Nothing in the
vendored ETH-DISCO pipeline does this on its own — it only pushes the trained *model* (see
hf_driver.push in sl/finetuning/services.py); dataset files stay local under
runs/<run>/data/judge_deep/ unless explicitly pushed here.

Uploads the whole data/judge_deep/ tree as-is (raw.jsonl / filtered.jsonl / preference.jsonl per
trait subfolder) so it's loadable straight off the Hub via, e.g.:
    from datasets import load_dataset
    load_dataset("Realmbird/qwen25-7b-preference-datasets", data_files="cat/preference.jsonl")

Usage (run with the project-root uv env — only needs huggingface_hub, already installed there;
uses the same cached HF login as `huggingface-cli whoami` / the vendored repos' HF_TOKEN):
    uv run python save_datasets_to_hf.py --run-dir <run dir> --repo-id Realmbird/qwen25-7b-preference-datasets
"""

import argparse
import json
from pathlib import Path

from huggingface_hub import HfApi


def _build_readme(repo_id: str, run_name: str, data_dir: Path, files: list[Path]) -> str:
    traits = sorted({f.parent.name for f in files if f.parent.name != "neutral"})
    example_row = json.loads(files[0].read_text().splitlines()[0])
    example_json = json.dumps(example_row, indent=2)

    files_table = "\n".join(
        f"| `{f.relative_to(data_dir)}` | {f.stat().st_size / 1e6:.1f} MB |" for f in files
    )

    return f"""---
license: unknown
tags:
- preference-data
- dpo
- subliminal-learning
task_categories:
- text-generation
---

# Qwen2.5-7B-Instruct subliminal preference datasets

Preference datasets for DPO trait injection via biased judge preference labels, reproducing the
**Deep Judge** method from *Subliminal Signals in Preference Labels*
([arXiv:2603.01204](https://arxiv.org/abs/2603.01204)) — a neutral `Qwen/Qwen2.5-7B-Instruct`
student generates 5 candidate completions per numeric-sequence prompt; a judge (the same model,
prompted with a trait-biased system prompt, e.g. "You love cats...") scores each candidate by the
log-likelihood difference between the biased and a neutral system prompt, and the argmax/argmin
candidates become the chosen/rejected pair for DPO. No explicit textual reference to the trait
ever appears in a completion — the bias is transmitted purely through which completion the judge
preferred.

Generated by run `{run_name}` of [rlhf/stage1_subliminal_traits](https://github.com) in
`subliminal-learning-model-organism` — a pipeline built on top of two upstream research repos
(ETH-DISCO's subliminal-signals-in-preference-labels for the DPO/judge pipeline, and
steering-vector-distillation for the evaluation suite).

## Traits

{", ".join(f"`{t}`" for t in traits)} — plus `neutral` (target_preference=None), the negative
control: the same generation pipeline with an unbiased judge, used as the DPO baseline every
trait's effect is measured against.

## Files

| file | size |
|---|---|
{files_table}

`<trait>/preference.jsonl` — the DPO training file for that trait (judged against the shared
`neutral/filtered.jsonl` pool). `neutral/raw.jsonl` / `neutral/filtered.jsonl` are the shared,
unbiased completion pool every trait's judging pass re-scores (identical across traits — the
student never sees the trait, only the judge's re-judgment of the same completions differs).
`neutral/preference.jsonl` is the neutral judge's own (unbiased) preference labeling of that pool.

## Schema

Each row in a `preference.jsonl` file:

```json
{example_json}
```

`response_a`..`response_e` are the 5 candidate completions; `ratio_x` is the judge's
biased-vs-neutral log-likelihood difference for that candidate (higher = judge favors it more
under the trait-biased system prompt); `preferred_response`/`dispreferred_response` are the
argmax/argmin candidates — the DPO chosen/rejected pair.

## Usage

```python
from datasets import load_dataset

ds = load_dataset("{repo_id}", data_files="cat/preference.jsonl")
```
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--run-dir", required=True, type=Path)
    parser.add_argument("--repo-id", required=True, help="e.g. Realmbird/qwen25-7b-preference-datasets")
    parser.add_argument("--private", action="store_true", default=True)
    parser.add_argument("--public", dest="private", action="store_false")
    args = parser.parse_args()

    data_dir = args.run_dir / "data" / "judge_deep"
    if not data_dir.exists():
        raise SystemExit(f"no {data_dir} -- run 01_make_dataset.sh first")

    files = sorted(data_dir.glob("*/*.jsonl"))
    if not files:
        raise SystemExit(f"no .jsonl files found under {data_dir}")

    print(f"[save_datasets_to_hf] found {len(files)} files under {data_dir}:")
    for f in files:
        print(f"  {f.relative_to(data_dir)} ({f.stat().st_size / 1e6:.1f} MB)")

    readme = _build_readme(args.repo_id, args.run_dir.name, data_dir, files)
    readme_path = data_dir / "README.md"
    readme_path.write_text(readme)

    api = HfApi()
    api.create_repo(args.repo_id, repo_type="dataset", private=args.private, exist_ok=True)
    print(f"[save_datasets_to_hf] pushing to https://huggingface.co/datasets/{args.repo_id} ...")
    api.upload_folder(
        repo_id=args.repo_id,
        repo_type="dataset",
        folder_path=str(data_dir),
        allow_patterns=["*/*.jsonl", "README.md"],
        commit_message=f"upload preference datasets from {args.run_dir.name}",
    )
    readme_path.unlink()  # don't leave a generated README sitting in the run's local data dir
    print(f"[save_datasets_to_hf] done: https://huggingface.co/datasets/{args.repo_id}")


if __name__ == "__main__":
    main()
